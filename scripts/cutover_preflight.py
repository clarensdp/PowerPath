"""Read-only cutover gate. Never stops writers or changes a backend on failure."""

import json
import os
import socket
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def assess():
    failures = []
    dsn = os.environ.get("POWERPATH_DATABASE_URL", "")
    required = [
        "POWERPATH_DATABASE_URL",
        "POWERPATH_PG_SCHEMA",
        "POWERPATH_SUPABASE_URL",
        "POWERPATH_SUPABASE_PUBLISHABLE_KEY",
    ]
    failures.extend("MISSING_CONFIGURATION:" + k for k in required if not os.environ.get(k))
    host = urlsplit(dsn.replace("postgresql+psycopg://", "postgresql://", 1)).hostname if dsn else None
    if not host:
        failures.append("DATABASE_HOST_NOT_CONFIGURED")
    else:
        try:
            socket.getaddrinfo(host, 5432, type=socket.SOCK_STREAM)
        except OSError:
            failures.append("DATABASE_HOST_UNREACHABLE")
    if os.environ.get("POWERPATH_IDENTITY_PROVIDER") != "supabase":
        failures.append("MANAGED_IDENTITY_NOT_CONFIGURED")
    if os.environ.get("POWERPATH_V27_AUTH_MODE") != "required":
        failures.append("REQUIRED_AUTH_NOT_CONFIGURED")
    report = ROOT / "docs/reports/TEST_REPORT_V30_8_1.json"
    if report.exists():
        results = json.loads(report.read_text())
        if not results.get("all_selected_passed"):
            failures.append("REGRESSION_GATE_FAILED")
        for key in ["postgres_live_parity_verified", "tenant_rls_runtime_verified", "browser_acceptance_verified"]:
            if not results.get(key):
                failures.append("UNVERIFIED:" + key)
    else:
        failures.append("REGRESSION_REPORT_MISSING")
    # Recovery evidence must be generated by a restore drill, not a manually
    # asserted flag. This preflight does not purport to validate that drill.
    if not (ROOT / "acceptance/restore-drill-result.json").is_file():
        failures.append("RESTORE_DRILL_EVIDENCE_MISSING")
    return {
        "cutover_executed": False,
        "preflight_passed": not failures,
        "blockers": failures,
        "database_secrets_included": False,
        "live_writers_modified": False,
    }


if __name__ == "__main__":
    result = assess()
    print(json.dumps(result, indent=2))
    raise SystemExit(0 if result["preflight_passed"] else 2)
